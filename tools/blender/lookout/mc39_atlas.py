"""Atlas layout for the MC-39 lookout: one 2048 px atlas shared by every material. Pure Python (no bpy).

Each entry: pixel rectangle (x, y, w, h; y down from the top of the image) and the physical size it stands for
(metres along u, metres along v). The pixels themselves are generated by mc39_textures.py.
"""
from mc39_mesh import Region

ATLAS_PX = 2048
N_STEEL = 6
N_WOOD = 6

_RECTS = {}
_y = 0
for _i in range(N_STEEL):                       # painted angle iron, joint end at u = 0
    _RECTS[f"STEEL{_i}"] = ((0, _y, 2048, 80), 4.2, 0.30)
    _y += 88
for _i in range(N_WOOD):                        # grey planks, along the grain
    _RECTS[f"WOOD{_i}"] = ((0, _y, 2048, 72), 4.6, 0.14)
    _y += 80
_RECTS.update({
    "PANEL0": ((0, 1008, 512, 256), 2.1336, 1.0668),      # cab lower wall, outside
    "PANEL1": ((520, 1008, 512, 256), 2.1336, 1.0668),
    "PANEL_IN": ((1040, 1008, 512, 256), 2.1336, 1.0668), # cab lower wall, inside
    "CONCRETE": ((1560, 1008, 256, 256), 1.0, 1.0),
    "MAPDISC": ((1824, 1008, 216, 216), 0.47, 0.47),
    "ROOF": ((0, 1272, 512, 288), 2.4384, 1.363),         # one hip sheet, eave along u
    "ROOF_UNDER": ((520, 1272, 256, 144), 2.4384, 1.363),
    "TREAD0": ((784, 1272, 304, 100), 0.6096, 0.2),       # perforated steel, alpha holes
    "TREAD1": ((1096, 1272, 304, 100), 0.6096, 0.2),
    "BRASS": ((1408, 1272, 512, 64), 1.0, 0.125),
    "DARK": ((1928, 1272, 48, 48), 1.0, 1.0),
    "PALE": ((1984, 1272, 48, 48), 1.0, 1.0),
    "GLASS0": ((784, 1380, 128, 160), 0.30, 0.375),       # dirty pane
    "GLASS1": ((920, 1380, 128, 160), 0.30, 0.375),       # dirty, cracked pane
    "SHARD": ((1056, 1380, 128, 160), 0.30, 0.375),
    "LEAVES": ((1192, 1380, 256, 160), 0.8, 0.5),         # leaf litter card, alpha
    "GALV": ((1456, 1344, 256, 64), 1.0, 0.25),           # bare galvanised (mast, yagi, hardware)
    "IMPOSTOR": ((0, 1568, 128, 472), 8.0, 33.0),         # distant billboard: u across 8 m, v up 33 m
})

REGIONS = {k: Region(k, r[0], ATLAS_PX, r[1], r[2]) for k, r in sorted(_RECTS.items())}


def region(name):
    return REGIONS[name]
